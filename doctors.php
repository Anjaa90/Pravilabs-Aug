            // Function to filter practitioners
            function filterPractitioners() {
                const city = document.getElementById("city-filter").value;
                const practice = document.getElementById("therapy-filter").value;
                const gender = document.querySelector("[name='gender']").value;
                const maxPrice = document.querySelector("[name='price']").value;
                const experienceFilter = document.getElementById("experience-filter").value;
        
                // Filter based on selected options
                const filtered = practitioners.filter(practitioner => {
                    const experienceMatch = experienceFilter === "any" ||
                        (experienceFilter === "0-5" && practitioner.experience <= 5) ||
                        (experienceFilter === "5-10" && practitioner.experience > 5 && practitioner.experience <= 10) ||
                        (experienceFilter === "10+" && practitioner.experience > 10);
        
                    return (
                        (city === "city" || practitioner.location === city) &&
                        (practice === "all-therapies" || practitioner.practice === practice) &&
                        (gender === "Gender" || practitioner.gender.toLowerCase() === gender.toLowerCase()) &&
                        (maxPrice === "any" || practitioner.price <= parseInt(maxPrice)) &&
                        experienceMatch
                    );
                });
        
                displayPractitioners(filtered);
            }
        
            // Event listeners for each filter
            document.getElementById("city-filter").addEventListener("change", filterPractitioners);
