<script>
    document.addEventListener("DOMContentLoaded", function () {
        document.querySelectorAll(".location li").forEach(item => {
            item.addEventListener("click", function (event) {
                event.stopPropagation();

                let dropdown = this.querySelector(".dropdown");
                let icon = this.querySelector("i");

                if (!dropdown) return;

                // Close other dropdowns and remove active class
                document.querySelectorAll(".dropdown").forEach(d => {
                    if (d !== dropdown) {
                        d.classList.remove("show");
                        let otherIcon = d.parentElement.querySelector("i");
                        if (otherIcon) otherIcon.style.transform = "rotate(0deg)";
                        d.parentElement.classList.remove("active");
                    }
                });

                document.querySelectorAll(".location li").forEach(li => {
                    li.classList.add("dimmed");
                });

                // Toggle the clicked dropdown
                if (dropdown.classList.contains("show")) {
                    dropdown.classList.remove("show");
                    icon.style.transform = "rotate(0deg)";
                    document.querySelectorAll(".location li").forEach(li => li.classList.remove("dimmed"));
                    this.classList.remove("active");
                } else {
                    dropdown.classList.add("show");
                    icon.style.transform = "rotate(180deg)";
                    this.classList.remove("dimmed");
                    this.classList.add("active");
                }
            });
        });

        // Close dropdowns when clicking outside
        document.addEventListener("click", function () {
            document.querySelectorAll(".dropdown").forEach(d => {
                d.classList.remove("show");
                let icon = d.parentElement.querySelector("i");
                if (icon) icon.style.transform = "rotate(0deg)";
                d.parentElement.classList.remove("active");
            });

            document.querySelectorAll(".location li").forEach(li => li.classList.remove("dimmed"));
        });
    });

</script>



